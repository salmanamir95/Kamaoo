class Product {
  final int id;
  final String name;
  final String image;
  final double price;
  final double rating;
  final int reviews;
  final bool isFavorite;

  Product({
    required this.id,
    required this.name,
    required this.image,
    required this.price,
    required this.rating,
    required this.reviews,
    required this.isFavorite,
  });
}
